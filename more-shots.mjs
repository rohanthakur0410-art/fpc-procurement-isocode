import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await page.goto('http://localhost:3000/login', { waitUntil: 'networkidle0' });
await page.type('input[autocomplete="username"]', 'office');
await page.type('input[type="password"]', 'demo1234');
await page.click('button[type="submit"]');
await new Promise(r => setTimeout(r, 1500));
await page.goto('http://localhost:3000/office/prices', { waitUntil: 'networkidle0' });
await new Promise(r => setTimeout(r, 900));
await page.screenshot({ path: '/tmp/shots/09-prices.png' });
await page.goto('http://localhost:3000/office/sms', { waitUntil: 'networkidle0' });
await new Promise(r => setTimeout(r, 900));
await page.screenshot({ path: '/tmp/shots/11-sms.png' });
console.log('done');
await browser.close();
